/**
 * Validates password strength. Returns { valid: boolean, message: string }.
 * Requires: 8+ characters, at least one uppercase, one lowercase, one
 * number, and one special character - a reasonable baseline for a real
 * deployment without being so strict it frustrates users.
 */
function validatePassword(password) {
  if (!password || typeof password !== 'string') {
    return { valid: false, message: 'Password is required' };
  }
  if (password.length < 8) {
    return { valid: false, message: 'Password must be at least 8 characters long' };
  }
  if (!/[A-Z]/.test(password)) {
    return { valid: false, message: 'Password must contain at least one uppercase letter' };
  }
  if (!/[a-z]/.test(password)) {
    return { valid: false, message: 'Password must contain at least one lowercase letter' };
  }
  if (!/[0-9]/.test(password)) {
    return { valid: false, message: 'Password must contain at least one number' };
  }
  if (!/[^A-Za-z0-9]/.test(password)) {
    return { valid: false, message: 'Password must contain at least one special character (e.g. !@#$%^&*)' };
  }
  return { valid: true, message: '' };
}

module.exports = { validatePassword };
