function reportTypeBadge(type) {
  const labels = { device: 'Device Inventory', security: 'Security', network_performance: 'Performance' };
  return labels[type] || type;
}

async function loadReports() {
  const container = document.getElementById('reportsList');
  container.innerHTML = '<div class="text-center text-muted py-4">Loading reports...</div>';

  try {
    const { reports } = await NetGuardianAPI.getReports();

    if (!reports.length) {
      container.innerHTML = '<div class="ng-empty-state">No reports generated yet.</div>';
      return;
    }

    container.innerHTML = reports.map((r) => `
      <div class="d-flex justify-content-between align-items-center py-2 border-bottom">
        <div>
          <div style="font-size:0.92rem; font-weight:600;">${r.title}</div>
          <div class="text-muted" style="font-size:0.78rem;">${reportTypeBadge(r.type)} &middot; generated by ${r.generatedBy?.name || 'system'} &middot; ${new Date(r.createdAt).toLocaleString()}</div>
        </div>
        <div class="d-flex gap-2">
          <button class="btn btn-sm btn-outline-secondary" onclick='viewReport(${JSON.stringify(r).replace(/'/g, "&apos;")})'>View</button>
          <button class="btn btn-sm btn-outline-secondary" onclick="downloadReportFile('${r._id}', '${r.title.replace(/'/g, "\\'")}', 'csv')">Download CSV</button>
          <button class="btn btn-sm btn-ng-gold" onclick="downloadReportFile('${r._id}', '${r.title.replace(/'/g, "\\'")}', 'pdf')">Download PDF</button>
        </div>
      </div>
    `).join('');
  } catch (err) {
    container.innerHTML = `<div class="text-danger">${err.message}</div>`;
  }
}

function viewReport(report) {
  alert(`${report.title}\n\n${JSON.stringify(report.summary, null, 2)}`);
}

/**
 * Downloads a report as a PDF or CSV. Uses fetch() with the auth header
 * (rather than a plain <a href> link) since the download endpoints are
 * protected - a normal link click wouldn't carry the JWT bearer token.
 */
async function downloadReportFile(reportId, title, format) {
  try {
    const url = format === 'csv'
      ? NetGuardianAPI.downloadReportCsvUrl(reportId)
      : NetGuardianAPI.downloadReportUrl(reportId);

    const res = await fetch(url, {
      headers: { Authorization: `Bearer ${getToken()}` }
    });

    if (!res.ok) {
      const data = await res.json().catch(() => ({}));
      throw new Error(data.message || `Download failed (${res.status})`);
    }

    const blob = await res.blob();
    const objectUrl = window.URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = objectUrl;
    a.download = `${title.replace(/[^a-z0-9]+/gi, '-').toLowerCase()}.${format}`;
    document.body.appendChild(a);
    a.click();
    a.remove();
    window.URL.revokeObjectURL(objectUrl);
  } catch (err) {
    alert(err.message);
  }
}

document.getElementById('genDeviceReport').addEventListener('click', async () => {
  try { await NetGuardianAPI.generateDeviceReport(); loadReports(); }
  catch (err) { alert(err.message); }
});

